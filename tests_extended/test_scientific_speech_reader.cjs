const assert = require('node:assert/strict');
const r = require('../assets/scientific_speech_reader.js');
const cubic=r.prepareText('Hàm số $y=x^3-3x+1$.','vi','Toán học');
assert.match(cubic,/mũ 3|lập phương/);
assert.match(r.prepareText('Ta có $\\frac{1}{\\sqrt{2}}$.','vi','Toán học'),/căn/);
assert.throws(()=>r.prepareText('Công thức $x^2','vi','Toán học'));
assert.throws(()=>r.prepareText('Công thức $\\unknowncmd{x}$','vi','Toán học'));
const words=Array.from({length:500},(_,i)=>'Từ'+i).join(' ');
assert.ok(r.planSpeech(words,'Ngữ văn','vi').at(-1).text.includes('Từ499'));
assert.match(r.prepareText('Vật có khối lượng 2 kg.','vi','Vật lý'),/ki lô gam/);
assert.doesNotMatch(r.prepareText('Tham số $y=2m+1$.','vi','Toán học'),/mét/);
assert.doesNotMatch(r.prepareText('Lực $F=2m$.','vi','Vật lý'),/mét/);
assert.match(r.prepareText('Chiều dài 2 m.','vi','Toán học'),/2 mét/);
assert.match(r.prepareText(String.raw`Ion $\ce{Na+}$.`,'vi','Hóa học'),/điện tích dương/);
assert.match(r.prepareText(String.raw`Ion $\ce{Cl-}$.`,'vi','Hóa học'),/điện tích âm/);
assert.match(r.prepareText(String.raw`Ion $\ce{Ca^2+}$.`,'vi','Hóa học'),/điện tích 2 dương/);
assert.match(r.prepareText(String.raw`Ion $\ce{Fe^{3+}}$.`,'vi','Hóa học'),/điện tích 3 dương/);
const reaction=r.prepareText(String.raw`$\ce{H2 + O2 -> H2O}$`,'vi','Hóa học');
assert.match(reaction,/cộng/);
assert.match(reaction,/tạo thành/);
assert.doesNotMatch(reaction,/điện tích/);
console.log(JSON.stringify({checks:16,cubic}));
